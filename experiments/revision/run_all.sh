#!/usr/bin/env bash
# run_all.sh - repeat all revision measurements on the KV260 and generate the data for the paper.
#
#   sudo ./run_all.sh                      full run (energy + timing grid), about 40 minutes
#   sudo PHASES=energy ./run_all.sh        energy only (about 30 minutes)
#
# What it does
#   1. builds revbench, puts the system in a quiet state and saves a snapshot of it
#   2. processor baselines (with an accelerator design loaded but idle):
#        idle power; energy of CPU-1 and CPU-4 (bound) at N=2^20 for all K;
#        timing grid: CPU-1 x1, CPU-4 bound x CPU4_BOUND_CAMPAIGNS, CPU-4 unbound x1
#   3. for every accelerator design in APPS: load it, idle power, energy (spin and sleep polling),
#        timing grid x1 (20 runs per configuration, every output verified)
#   4. idle power again at the end, then analyze.py -> tables (results_*/tables) and figure data
#      (results_*/figdata), then make_figures.py -> figures (results_*/figures, PDF + PNG)
# Repeated trials are always summarized as median (timing) or mean (energy) +- standard deviation.
# Power and temperatures are logged during every phase.
#
# Edit the CONFIG block first. Register offsets: check x<kernel>_hw.h generated by Vitis HLS.
set -euo pipefail

# ------------------------------------------------------------------ CONFIG
APPS=${APPS:-"P1:microbench:100:128 P4:microbench_p4:100:32"}
# one entry per design: tag:xmutil-app:PL-clock-MHz:width of M_AXI_HPM0_FPD in that design (32/64/128).
# The PS side of M_AXI_HPM0_FPD (register AFI_FS) is set to that width after loading the design:
# xmutil does not do it, and a mismatch silently discards control-register writes (see the paper).
                                                     # e.g. add "P1c200:microbench_p1_200:200" for the clock test
APP_FOR_CPU=${APP_FOR_CPU:-microbench}             # design loaded (idle) while the processor runs
FPL_MHZ=${FPL_MHZ:-100}                              # PL clock (used by the analysis only)
CTRL_BASE=${CTRL_BASE:-0xA0000000}                   # s_axi_control base address
UDMABUF=${UDMABUF:-udmabuf0}                         # u-dma-buf device name
REG_OFFSETS=${REG_OFFSETS:-"--off-in 0x10 --off-out 0x1c --off-n 0x28 --off-k 0x30"}
PHASES=${PHASES:-"energy grid"}
SKIP_CPU=${SKIP_CPU:-0}                              # 1 = do not repeat the processor baselines
ENERGY_N=${ENERGY_N:-1048576}
ENERGY_SECONDS=${ENERGY_SECONDS:-10}
ENERGY_REPEATS=${ENERGY_REPEATS:-3}                  # independent repetitions per energy configuration (-> SD)
IDLE_SECONDS=${IDLE_SECONDS:-60}
COOLDOWN=${COOLDOWN:-5}
GRID_REPS=${GRID_REPS:-20}
GRID_SET=${GRID_SET:-""}                             # e.g. "--ns 1024,4096 --ks 1,16" for a quick test
CPU4_BOUND_CAMPAIGNS=${CPU4_BOUND_CAMPAIGNS:-5}
ACC_POLL_VARIANTS=${ACC_POLL_VARIANTS:-"spin sleep"}
DRY_RUN=${DRY_RUN:-0}                                # 1 = test the pipeline without hardware
# ------------------------------------------------------------------

HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-$HERE/results_$(date +%Y%m%d_%H%M%S)}
mkdir -p "$OUT"/{power,energy,grid,state,logs,tables}
exec > >(tee -a "$OUT/logs/run_all.log") 2>&1
log() { echo "[$(date +%H:%M:%S)] $*"; }
has() { [[ " $PHASES " == *" $1 "* ]]; }

if [[ $DRY_RUN != 1 && $(id -u) != 0 ]]; then echo "Run with sudo."; exit 1; fi

log "building revbench"
g++ -O3 -std=c++17 -fopenmp -o "$HERE/revbench" "$HERE/revbench.cpp"

if [[ $DRY_RUN == 1 ]]; then
  FAKE="$OUT/fakesys"; mkdir -p "$FAKE/class/hwmon/hwmon0"
  echo ina260_u14 > "$FAKE/class/hwmon/hwmon0/name"; echo 3500000 > "$FAKE/class/hwmon/hwmon0/power1_input"
  LOGGER=(python3 "$HERE/power_logger.py" --sysfs-root "$FAKE")
  ACC_EXTRA=(--dry-run)
else
  "$HERE/quiet_system.sh" "$OUT/state/system_state.txt"
  { echo "# g++: $(g++ --version | head -1)"; echo "# apps:"; xmutil listapps 2>/dev/null | sed 's/^/#   /'; } \
    >> "$OUT/state/system_state.txt"
  LOGGER=(python3 "$HERE/power_logger.py" --rt --child-nice -20)
  ACC_EXTRA=(--ctrl "$CTRL_BASE" --udmabuf "$UDMABUF" $REG_OFFSETS)
fi
BENCH="$HERE/revbench"
BOUND=(OMP_NUM_THREADS=4 OMP_PROC_BIND=close OMP_PLACES=cores)
UNBOUND=(OMP_NUM_THREADS=4)
echo "tag,k,n,rep,out,power,idle" > "$OUT/energy/index.csv"
echo "tag,fpl_mhz" > "$OUT/energy/fpl.csv"

set_hpm_width() {   # set_hpm_width <32|64|128>: PS side of M_AXI_HPM0_FPD (AFI_FS bits 9:8)
  [[ -z $1 || $DRY_RUN == 1 ]] && return 0
  python3 - "$1" <<'PYEOF'
import mmap, os, sys
code = {'32': 0, '64': 1, '128': 2}[sys.argv[1]]
m = mmap.mmap(os.open('/dev/mem', os.O_RDWR | os.O_SYNC), 0x1000, offset=0xFD615000)  # FPD_SLCR AFI_FS
r = memoryview(m).cast('I')
old = r[0]
r[0] = (old & ~0x300) | (code << 8)
print(f'    AFI_FS: {old:#06x} -> {r[0]:#06x} (M_AXI_HPM0_FPD {sys.argv[1]}-bit)')
PYEOF
}
load_app() {
  log "loading design $1"
  [[ $DRY_RUN == 1 ]] && return 0
  xmutil unloadapp >/dev/null 2>&1 || true
  xmutil loadapp "$1"
  sleep 3
}
idle() {   # idle <state>
  log "idle power ($1), ${IDLE_SECONDS} s"
  "${LOGGER[@]}" --hz 50 --idle "$IDLE_SECONDS" --out "$OUT/power/idle_$1.csv" | tee "$OUT/energy/idle_$1.txt"
}
energy() { # energy <tag> <idle-state> <mode> <env...> -- <revbench extra args...>
  local tag=$1 st=$2 mode=$3; shift 3
  local envs=(); while [[ $# -gt 0 && $1 != -- ]]; do envs+=("$1"); shift; done; shift || true
  for r in $(seq 1 "$ENERGY_REPEATS"); do
  for k in 1 4 16 64 256; do
    local base="E_${tag}_K${k}_r$r"
    log "energy $tag K=$k (repetition $r/$ENERGY_REPEATS)"
    env "${envs[@]}" "${LOGGER[@]}" --hz 50 --out "$OUT/power/$base.csv" -- \
      "$BENCH" --mode "$mode" --n "$ENERGY_N" --k "$k" --seconds "$ENERGY_SECONDS" --tag "$tag" "$@" \
      > "$OUT/energy/$base.out"
    grep -h "mean_power" "$OUT/energy/$base.out" | sed 's/^/    /'
    echo "$tag,$k,$ENERGY_N,$r,energy/$base.out,power/$base.csv,power/idle_$st.csv" >> "$OUT/energy/index.csv"
    sleep "$COOLDOWN"
  done
  done
}
grid() {   # grid <tag> <mode> <campaign> <env...> -- <revbench extra args...>
  local tag=$1 mode=$2 camp=$3; shift 3
  local envs=(); while [[ $# -gt 0 && $1 != -- ]]; do envs+=("$1"); shift; done; shift || true
  log "timing grid $tag campaign $camp"
  env "${envs[@]}" "${LOGGER[@]}" --hz 5 --out "$OUT/power/G_${tag}_c$camp.csv" -- \
    "$BENCH" --mode "$mode" --grid --reps "$GRID_REPS" --tag "$tag" --campaign "$camp" \
    --csv "$OUT/grid/grid.csv" $GRID_SET "$@" > "$OUT/logs/G_${tag}_c$camp.log" 2>&1
  sleep "$COOLDOWN"
}

# ------------------------------------------------------------------ processor baselines
if [[ $SKIP_CPU != 1 ]]; then
load_app "$APP_FOR_CPU"
idle cpu
if has energy; then
  energy CPU1 cpu cpu1 --
  energy CPU4 cpu cpu4 "${BOUND[@]}" --
fi
if has grid; then
  grid CPU1 cpu1 1 --
  for c in $(seq 1 "$CPU4_BOUND_CAMPAIGNS"); do grid CPU4b cpu4 "$c" "${BOUND[@]}" --; done
  grid CPU4u cpu4 1 "${UNBOUND[@]}" --
fi
fi

# ------------------------------------------------------------------ accelerators
for entry in $APPS; do
  IFS=: read -r tag app fpl hpm <<< "$entry"
  [[ -z $fpl ]] && fpl=$FPL_MHZ
  load_app "$app"
  set_hpm_width "$hpm"
  echo "# $tag: app=$app fpl=$fpl MHz M_AXI_HPM0_FPD=${hpm:-unchanged}-bit" >> "$OUT/state/system_state.txt"
  idle "$tag"
  echo "$tag,$fpl" >> "$OUT/energy/fpl.csv"
  if has energy; then
    for pv in $ACC_POLL_VARIANTS; do
      etag=$tag; [[ $pv != spin ]] && etag="${tag}_${pv}"
      energy "$etag" "$tag" acc -- "${ACC_EXTRA[@]}" --poll "$pv"
    done
  fi
  if has grid; then grid "$tag" acc 1 -- "${ACC_EXTRA[@]}" --poll spin; fi
done
idle end

# ------------------------------------------------------------------ analysis
log "analysis"
python3 "$HERE/analyze.py" "$OUT" --fpl "$FPL_MHZ" | tee "$OUT/tables/summary.txt"
if python3 -c "import matplotlib" 2>/dev/null; then
  python3 "$HERE/make_figures.py" "$OUT"
else
  log "matplotlib not installed here: run  python3 make_figures.py <results_dir>  on the PC"
fi
tar -C "$(dirname "$OUT")" -czf "$OUT.tar.gz" "$(basename "$OUT")"
log "done: $OUT  (archive: $OUT.tar.gz)"
